// Regenerates src/generated/schema.d.ts from a Wavvon-docs checkout and
// records the docs commit it came from in src/generated/SPEC_COMMIT.
//
//   node scripts/generate.mjs [docs-path] [--ref <git-ref>]
//
// docs-path defaults to ../../docs (the monorepo layout). With --ref the spec
// is read from that commit instead of the working tree, so a regeneration can
// be pinned without checking anything out.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = fileURLToPath(new URL("..", import.meta.url));
const args = process.argv.slice(2);
const refAt = args.indexOf("--ref");
const ref = refAt >= 0 ? args.splice(refAt, 2)[1] : null;
const docs = resolve(here, args[0] ?? "../../docs");

const git = (...a) => execFileSync("git", ["-C", docs, ...a], { encoding: "utf8" }).trim();

let commit = git("rev-parse", ref ?? "HEAD");
let spec = ref
  ? git("show", `${commit}:openapi.yaml`)
  : readFileSync(resolve(docs, "openapi.yaml"), "utf8");
// A spec with local edits is not the commit it claims to be.
if (!ref && git("status", "--porcelain", "--", "openapi.yaml") !== "") commit += "-dirty";

// Schemas the spec references but does not define, written from the hub's
// own serde types. Each one is a spec bug: fix it in Wavvon-docs and the
// entry stops applying (it is only inserted while the name is missing).
const SPEC_GAPS = {
  // crates/hub/src/routes/apps/models.rs, AppMeResponse
  AppRegistration: `
    AppRegistration:
      type: object
      required: [pubkey, name, commands]
      properties:
        pubkey: { type: string }
        name: { type: string }
        avatar_url: { type: string }
        description: { type: string }
        webhook_url: { type: string }
        homepage_url: { type: string }
        commands:
          type: array
          items:
            type: object
            required: [name, description]
            properties:
              name: { type: string }
              description: { type: string }
              args: { type: string }
              scope: { type: string }
              privileged: { type: boolean }
              cooldown_seconds: { type: integer }`,
};
for (const [name, yaml] of Object.entries(SPEC_GAPS)) {
  const referenced = spec.includes(`#/components/schemas/${name}`);
  const defined = new RegExp(`^ {4}${name}:`, "m").test(spec);
  if (referenced && !defined) {
    console.warn(`WARNING: openapi.yaml references ${name} but never defines it; patching it in. Fix the spec.`);
    spec = spec.replace(/^ {2}schemas:\r?\n/m, (m) => m + yaml.replace(/^\n/, "") + "\n");
    commit += `+${name}`;
  }
}

const ast = await openapiTS(spec);
const header = `// Generated by scripts/generate.mjs from Wavvon-docs openapi.yaml @ ${commit}.\n// Do not edit by hand: regenerate instead.\n\n`;
writeFileSync(resolve(here, "src/generated/schema.d.ts"), header + astToString(ast));
writeFileSync(resolve(here, "src/generated/SPEC_COMMIT"), commit + "\n");
console.log(`schema.d.ts generated from Wavvon-docs ${commit}`);
